// Generates prisma/postgres/schema.prisma from the SQLite dev schema by swapping the provider.
// Postgres has its own migrations folder (prisma/postgres/migrations) because SQL differs per engine.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'prisma', 'schema.prisma'), 'utf8');
const out = src.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
if (out === src) throw new Error('sqlite provider not found in prisma/schema.prisma');
mkdirSync(join(root, 'prisma', 'postgres'), { recursive: true });
writeFileSync(
  join(root, 'prisma', 'postgres', 'schema.prisma'),
  '// GENERATED by scripts/prisma-postgres.mjs. Edit prisma/schema.prisma instead.\n' + out,
);
console.log('Wrote prisma/postgres/schema.prisma');
